"""领域纠错：ASR 常见的同音字错误。

按实际使用逐步补充——每发现一次错，就加一条。
"""
from __future__ import annotations

# 顺序执行，长串优先
FIXES: list[tuple[str, str]] = [
    ("若网", "弱网"),
    ("时言", "时延"),
    ("时研", "时延"),
    ("韦度", "纬度"),
    ("三期开", "三七开"),
    ("四期开", "四七开"),
    ("POP环境", "POC环境"),
    ("泡泡环境", "POC环境"),
    ("落网", "弱网"),
    ("纬路", "纬度"),
    ("POC环境", "POC环境"),
    ("pop环境", "POC环境"),
    ("两秒一次", "两秒一次"),
    ("若网", "弱网"),
    ("推完了", "推完了"),
    ("四星云端", "四星云桌面"),
    ("POP 环境", "POC 环境"),
    ("吊顶", "调顶"),
    ("云桌面的", "云桌面的"),
    ("硬解兼容性", "硬解兼容性"),
    ("龙芯和麒麟", "龙芯和麒麟"),
    ("丢包率", "丢包率"),
]


def fix(text: str) -> str:
    for bad, good in FIXES:
        if bad in text:
            text = text.replace(bad, good)
    return text
